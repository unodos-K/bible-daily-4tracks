function getDateFromDayIndex(dayIndex, year) {
  const date = new Date(year, 0, 1);
  date.setDate(dayIndex);
  return {
    formatted: date.toISOString().split('T')[0],
    month: date.getMonth() + 1,
    day: date.getDate()
  };
}

function parseRange(rangeStr) {
  const trimmed = rangeStr.trim();
  
  const parts = trimmed.split("/");
  let textToParse = parts[0].trim();
  const book = textToParse.split(" ")[0];

  const rest = textToParse.slice(book.length).trim();
  const cleanRest = rest.replace(/\s*\([^)]*\)$/, "").trim();

  let startChapter = null;
  let endChapter = null;
  let startVerse = null;
  let endVerse = null;

  // "150:6"
  let m = cleanRest.match(/^(\d+):(\d+)$/);
  if (m) {
    startChapter = parseInt(m[1], 10);
    endChapter = startChapter;
    startVerse = parseInt(m[2], 10);
    endVerse = startVerse;
    return { range: trimmed, book, startChapter, endChapter, startVerse, endVerse };
  }

  // "6:14~7:25"
  m = cleanRest.match(/^(\d+):(\d+)~(\d+):(\d+)$/);
  if (m) {
    startChapter = parseInt(m[1], 10);
    startVerse = parseInt(m[2], 10);
    endChapter = parseInt(m[3], 10);
    endVerse = parseInt(m[4], 10);
    return { range: trimmed, book, startChapter, endChapter, startVerse, endVerse };
  }

  // "5~6:13" or "117~118:14"
  m = cleanRest.match(/^(\d+)~(\d+):(\d+)$/);
  if (m) {
    startChapter = parseInt(m[1], 10);
    startVerse = null;
    endChapter = parseInt(m[2], 10);
    endVerse = parseInt(m[3], 10);
    return { range: trimmed, book, startChapter, endChapter, startVerse, endVerse };
  }

  // "24:1~33" or "5:1~26" or "119:1~8"
  m = cleanRest.match(/^(\d+):(\d+)~(\d+)$/);
  if (m) {
    startChapter = parseInt(m[1], 10);
    endChapter = parseInt(m[1], 10);
    startVerse = parseInt(m[2], 10);
    endVerse = parseInt(m[3], 10);
    return { range: trimmed, book, startChapter, endChapter, startVerse, endVerse };
  }

  // "1~2장" or "1~2편"
  m = cleanRest.match(/^(\d+)~(\d+)[장편]$/);
  if (m) {
    startChapter = parseInt(m[1], 10);
    endChapter = parseInt(m[2], 10);
    startVerse = null;
    endVerse = null;
    return { range: trimmed, book, startChapter, endChapter, startVerse, endVerse };
  }

  // "1장" or "1편"
  m = cleanRest.match(/^(\d+)[장편]$/);
  if (m) {
    startChapter = parseInt(m[1], 10);
    endChapter = parseInt(m[1], 10);
    startVerse = null;
    endVerse = null;
    return { range: trimmed, book, startChapter, endChapter, startVerse, endVerse };
  }
  
  // "150:3"
  m = cleanRest.match(/^(\d+):(\d+)$/);
  if (m) {
    startChapter = parseInt(m[1], 10);
    endChapter = parseInt(m[1], 10);
    startVerse = parseInt(m[2], 10);
    endVerse = parseInt(m[2], 10);
    return { range: trimmed, book, startChapter, endChapter, startVerse, endVerse };
  }

  throw new Error("Could not parse rest of range: " + rest + " (full: " + trimmed + ")");
}

const lines = rawText.split('\n').filter(l => l.trim() !== "");

const schedule = lines.map(line => {
  const parts = line.split("|").map(p => p.trim());
  if (parts.length !== 5) {
    throw new Error("Line parts not equal to 5: " + line);
  }

  const dayStr = parts[0]; // "Day 1"
  const dayIndex = parseInt(dayStr.replace("Day ", ""), 10);
  
  const { formatted, month, day } = getDateFromDayIndex(dayIndex, 2026);

  const tracks = [
    { type: "OLD", title: "구약", ...parseRange(parts[1]) },
    { type: "NEW", title: "신약", ...parseRange(parts[2]) },
    { type: "PSALMS", title: "시편", ...parseRange(parts[3]) },
    { type: "PROVERBS", title: "잠언", ...parseRange(parts[4]) }
  ];

  return {
    dayIndex,
    date: formatted,
    month,
    day,
    tracks
  };
});

